import pickle, json, base64, struct, os
from shapely.geometry import Polygon
F,res=pickle.load(open('stage2.pkl','rb'))
KMAP=['green','tee','fairway','bunker','rough','water_hazard','lateral_water_hazard','wood','scrub','wetland','beach']
used=sorted({i for c in res for r in res[c].values() for i in r['f']}|{r['gi'] for c in res for r in res[c].values() if r['gi'] is not None}|{r['ti'] for c in res for r in res[c].values() if r['ti'] is not None})
remap={o:n for n,o in enumerate(used)}
def flat(coords): 
    o=[]
    for x,y in coords: o+= [int(round(x*2)),int(round(y*2))]
    return o
polys=[]
for i in used:
    g=F[i]['g'].simplify(0.7)
    if g.is_empty or not isinstance(g,Polygon): g=F[i]['g']
    rings=[flat(list(g.exterior.coords)[:-1])]+[flat(list(r.coords)[:-1]) for r in g.interiors if Polygon(r).area>4]
    polys.append([KMAP.index(F[i]['k']),rings])
holes={}
for c in res:
    holes[c]={}
    for n,r in res[c].items():
        holes[c][int(n)]={'r':flat(r['route']),'g':flat([r['green']]),'gi':remap.get(r['gi'],-1),'ti':remap.get(r['ti'],-1),'f':[remap[i] for i in r['f']],'len':r['len'],'osm':r['osm'],'note':r['note']}
frame={}
dem=None
if os.path.exists('dem.json'):
    d=json.load(open('dem.json'))
    z=[0 if v is None else v for v in d['z']]
    mn=min(z);mx=max(z)
    b=struct.pack('<%dh'%len(z),*[int(round(v*10)) for v in z])
    frame=dict(lat0=d['lat0'],lon0=d['lon0'],mlat=d['mlat'],mlon=d['mlon'],E0=d['E0'],N0=d['N0'],step=d['step'],cols=d['cols'],rows=d['rows'])
    dem=base64.b64encode(b).decode()
    print('dem',len(z),mn,mx,len(dem))
else:
    print('no dem yet')
js='/* Real-world coastal course geometry. Hole routes, greens, tees, bunkers, fairways, rough, water and woods from OpenStreetMap (© OpenStreetMap contributors, ODbL). Elevation: USGS NED 10 m via OpenTopoData. Generated by tools/. */\nwindow.BG=window.BG||{};BG.Real='+json.dumps({'frame':frame,'kinds':KMAP,'dem':dem,'poly':polys,'holes':holes},separators=(',',':'),default=int)+';\n'
open('/workspace/bandon-golf/js/realdata.js','w').write(js)
print(len(js)//1024,'KB',len(polys),'polys')
